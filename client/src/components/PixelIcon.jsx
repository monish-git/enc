export default function PixelIcon({ name, size = 16, className = '', title }) {
  const rects = ICONS[name] || ICONS.folder;
  return (
    <svg
      className={`px ${className}`}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
    >
      {rects.map(([x, y, w, h, c], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} fill={C[c]} />
      ))}
    </svg>
  );
}
